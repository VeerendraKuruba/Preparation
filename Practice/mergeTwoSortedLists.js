var mergeTwoLists = function(list1, list2) {
  const dummy = new ListNode(0);
  let current = dummy;

  while (list1 && list2) {
    if (list1.val <= list2.val) {
      current.next = list1;
      list1 = list1.next;
    } else {
      current.next = list2;
      list2 = list2.next;
    }
    current = current.next;
  }

  current.next = list1 || list2;
  return dummy.next;
};

class ListNode {
  constructor(val = 0, next = null) {
    this.val = val;
    this.next = next;
  }
}

function buildList(arr) {
  let dummy = new ListNode(0), cur = dummy;
  for (const v of arr) {
    cur.next = new ListNode(v);
    cur = cur.next;
  }
  return dummy.next;
}

const list1 = buildList([1, 3, 5]);
const list2 = buildList([2, 4, 6]);
const merged = mergeTwoLists(list1, list2);

let node = merged;
const values = [];
while (node) {
  values.push(node.val);
  node = node.next;
}
console.log('list1:     ', [1, 3, 5]);
console.log('list2:     ', [2, 4, 6]);
console.log('merged:    ', values);
